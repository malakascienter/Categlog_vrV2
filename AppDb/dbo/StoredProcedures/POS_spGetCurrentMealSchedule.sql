CREATE     PROCEDURE [dbo].[POS_spGetCurrentMealSchedule]
AS
SET NOCOUNT ON
BEGIN TRY
	BEGIN TRAN

		SELECT MealCode, Meal FROM POS_MealSchedule WHERE	CONVERT(TIME,GETDATE()) BETWEEN CONVERT(TIME,FromTime) AND CONVERT(TIME,ToTime)

	COMMIT TRAN 
END TRY

BEGIN CATCH
	ROLLBACK TRAN
	DECLARE @Msg NVARCHAR(200)
	SET @Msg = ERROR_MESSAGE()
	INSERT INTO POS_DatabaseErrorLog (ErrorNumber,ErrorSeverity,ErrorState,ErrorProcedure,ErrorLine,ErrorMessage)	
    VALUES (ERROR_NUMBER(),ERROR_SEVERITY(),ERROR_STATE(),ERROR_PROCEDURE(),ERROR_LINE(),@Msg)
	RAISERROR(@Msg,16,1)
END CATCH

GO

