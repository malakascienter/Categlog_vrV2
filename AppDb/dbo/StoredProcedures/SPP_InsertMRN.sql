  FROM     OPENXML (@iDocID,'/MRNRequestHeader/DetailList/MRNRequestDetail',2)
  With (StockItemID int ,RequestedQuantity decimal(18,2),UnitPrice decimal(18,2),IsSundry BIT)

  Declare @SundryTotal Decimal(18,2) 

  Select @SundryTotal=sum(RequestedQuantity*UnitPrice) from #tempSundry where IsSundry=1

	If(@SundryTotal IS NOT NULL)
	BEGIN
	  update SundryRegistries 
  SET	BalanceAmount= BalanceAmount-@SundryTotal,
		RequestAmount=RequestAmount+@SundryTotal 
	Where BOQId=@BoqID AND DepId=@DepartmentIdSundry

	END


	


